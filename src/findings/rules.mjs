// Rule catalog: every flag code any tool can emit -> concept (remedy), WCAG SCs, kind, base confidence, base severity.
// kind: failure (WCAG A/AA candidate) | best-practice | aaa | advisory | not-tested | other-risk | info (dropped from reports).
// confidence: automated-certain (deterministic DOM/axe fact) | needs-review (heuristic; confirm in DOM + screenshot) | inferred (static cue / root cause guess).
// group: findings with the same group are merged across tools and pages (dedupe). Default group = `${concept}:${sc[0]}:${kind}`.

/** @typedef {'failure'|'best-practice'|'aaa'|'advisory'|'not-tested'|'other-risk'|'info'} Kind */
/** @typedef {'automated-certain'|'needs-review'|'inferred'} Confidence */
/** @typedef {'blocker'|'critical'|'serious'|'moderate'|'minor'} Severity */
/** @typedef {{id:string, tool:string, code:string, concept:string, sc:string[], kind:Kind, confidence:Confidence, severity:Severity, title?:string, group?:string, re?:RegExp}} Rule */

const C = 'automated-certain',
  N = 'needs-review',
  I = 'inferred';
/** @type {Rule[]} */
export const RULES = [];
function def(tool, rows) {
  for (const [code, concept, sc, kind, confidence, severity, extra = {}] of rows)
    RULES.push({
      id: `${tool}/${code.replace(/[?()]/g, '').replace(/\s+/g, '-').toLowerCase()}`,
      tool,
      code,
      concept,
      sc,
      kind,
      confidence,
      severity,
      ...extra,
    });
}

