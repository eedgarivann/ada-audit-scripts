const byTool = new Map();
for (const r of RULES) {
  if (!byTool.has(r.tool)) byTool.set(r.tool, []);
  byTool.get(r.tool).push(r);
}
/** Rules a tool can emit, longest code first (so PARTLY-COVERED wins over COVERED). */
export function rulesFor(tool) {
  return [...(byTool.get(tool) || [])].sort((a, b) => b.code.length - a.code.length);
}
export function groupOf(rule) {
  return rule.group || `${rule.concept}:${rule.sc[0] || '-'}:${rule.kind}`;
}
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** Regex that matches a rule's code as a whole token in a tool output line. */
export function ruleRegex(rule) {
  return rule.re || new RegExp(`(?<![A-Z0-9-])${esc(rule.code.replace(/\?$/, ''))}\\??(?![A-Z0-9-])`);
}
